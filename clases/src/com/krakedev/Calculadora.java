package com.krakedev;

public class Calculadora {
	public double Sumar(double a, double b) {
		
		double resultado;
	resultado = a + b ;
	return resultado;
	}
	
	public int restar(int a, int b) {
		
		int resultado;
		resultado = a - b;
		return resultado;
	}
public double Multiplicar(double a, double b) {
		
		double resultado;
	resultado = a * b ;
	return resultado;
	}

public double Diovidir(double a, double b) {
	
	double resultado;
resultado = a / b ;
return resultado;
}

public double Promedio(double a, double b, double c ) {
	
	double resultado;
	resultado = (a + b + c)/3 ;
	return resultado;
}
	

}
